def norm(s):
    s = (s or u"").lower().replace(u"ё", u"е")
    return re.sub(u"[^a-zа-я0-9]+", u" ", s).strip()


def main():
    pool = [json.loads(l) for l in io.open(POOL, encoding="utf-8") if l.strip()]
    texts = {}
    for r in pool:
        texts[r["id"]] = norm(r["text"])
    # покрытие существующими разделами
    covered = Counter()
    residual = []
    key_rx = {}
    for sec, keys in SECTION_KEYS.items():
        key_rx[sec] = re.compile(u"(?:^| )(?:%s)" %
                                 u"|".join(re.escape(k) for k in keys))
    for r in pool:
        t = texts[r["id"]]
        hit = [sec for sec in SECTION_KEYS if key_rx[sec].search(u" " + t)]
        if hit:
            for sec in hit:
                covered[sec] += 1
        else:
            residual.append(r)

    uni = Counter()
    bi = Counter()
    for r in residual:
        ws = [w for w in texts[r["id"]].split() if len(w) >= 5 and w not in STOP]
        uni.update(set(ws))
        bi.update(set(u" ".join(ws[i:i + 2]) for i in range(len(ws) - 1)))

    lines = [u"пул сообщений, задающих тему: %d" % len(pool),
             u"не зацеплен ни одним ключом существующего раздела: %d (%.1f%%)" %
             (len(residual), 100.0 * len(residual) / len(pool)),
             u"", u"покрытие (сколько сообщений пула содержит ключ раздела,"
                  u" пересечения возможны):"]
    for sec in sorted(covered, key=lambda s: -covered[s]):
        lines.append(u"  раздел %2d: %d" % (sec, covered[sec]))
    lines.append(u"")
    lines.append(u"топ-160 слов остатка (сколько сообщений):")
    for w, c in uni.most_common(160):
        lines.append(u"  %-22s %d" % (w, c))
    lines.append(u"")
    lines.append(u"топ-120 пар слов остатка:")
    for w, c in bi.most_common(120):
        if c >= 3:
            lines.append(u"  %-34s %d" % (w, c))
    io.open(TOP, "w", encoding="utf-8", newline=u"\n").write(u"\n".join(lines))

    # по каждому частотному слову остатка — примеры сообщений
    by_word = defaultdict(list)
    for r in residual:
        for w in set(texts[r["id"]].split()):
            if len(w) >= 5 and w not in STOP and uni[w] >= 12:
                by_word[w].append(r)
    out = []
    for w, c in uni.most_common(400):
        rows = by_word.get(w, [])
        if c < 12:
            continue
        rows.sort(key=lambda r: -len(r["text"]))
        out.append(u"### %s — %d сообщений" % (w, c))
        for r in rows[:3]:
            t = re.sub(u"\\s+", u" ", r["text"])[:190]
            out.append(u"  (#%s, %s) %s" % (r["id"], r["date"][:10], t))
        out.append(u"")
    io.open(RES, "w", encoding="utf-8", newline=u"\n").write(u"\n".join(out))
    with io.open(RESJSONL, "w", encoding="utf-8", newline=u"\n") as f:
        for r in residual:
            f.write(json.dumps({"id": r["id"], "date": r["date"],
                                "text": r["text"]}, ensure_ascii=False) + u"\n")
    print(u"residual=%d words=%d sections_reported=%d" %
          (len(residual), len(uni), len(covered)))
    return 0


