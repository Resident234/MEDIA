def main():
    txt = io.open(MD, "r", encoding="utf-8").read()
    block = io.open(BLOCK, "r", encoding="utf-8").read().rstrip(u"\n")
    lines = txt.split(u"\n")
    try:
        si = next(i for i, l in enumerate(lines) if l.strip() == START)
    except StopIteration:
        raise SystemExit("START marker not found")
    ei = next(i for i in range(si + 1, len(lines))
              if lines[i].strip().startswith(NEXT))
    before = lines[:si]
    after = lines[ei:]
    # хвост старого блока: сохраняем строку `Важная деталь...` и региональные
    # ссылки, если они были внутри заменяемого диапазона.
    old_mid = lines[si:ei]
    keep = []
    grab = False
    for l in old_mid:
        s = l.strip()
        if s.startswith(u"\u0412\u0430\u0436\u043d\u0430\u044f \u0434\u0435\u0442\u0430\u043b\u044c"):
            grab = True
        if grab:
            keep.append(l)
    kept = u"\n".join(keep).strip(u"\n")
    seg = HEADER + block + u"\n\n" + kept + u"\n"
    new = u"\n".join(before) + u"\n" + seg + u"\n".join(after)
    io.open(MD, "w", encoding="utf-8", newline="\n").write(new)
    print("integrated: replaced %d lines with %d (kept tail %d lines)"
          % (ei - si, seg.count("\n") + 1, len(keep)))


if __name__ == "__main__":
    main()
